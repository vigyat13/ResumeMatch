import type { ResumeData } from './types'

function esc(s: string): string {
  return s
    .replace(/\\/g, '\\textbackslash{}')
    .replace(/&/g,  '\\&')
    .replace(/%/g,  '\\%')
    .replace(/\$/g, '\\$')
    .replace(/#/g,  '\\#')
    .replace(/_/g,  '\\_')
    .replace(/\{/g, '\\{')
    .replace(/\}/g, '\\}')
    .replace(/~/g,  '\\textasciitilde{}')
    .replace(/\^/g, '\\textasciicircum{}')
    .replace(/→/g,  '$\\rightarrow$')
    .replace(/–/g,  '--')
    .replace(/—/g,  '---')
    .replace(/★/g,  '$\\star$')
    .replace(/•/g,  '\\textbullet{}')
}

// Normalize a URL the user typed so we always emit a valid `https://…` href
// without ever double-prefixing (e.g. `https://https://github.com/…`).
// Returns { display, href } — display strips the scheme so the printed
// link reads cleanly ("github.com/foo"), while href keeps the full URL.
function normalizeUrl(raw: string): { display: string; href: string } {
  const trimmed = raw.trim().replace(/^https?:\/\//i, '').replace(/\/$/, '')
  return { display: trimmed, href: `https://${trimmed}` }
}

function linkPart(raw: string | undefined | null): string {
  if (!raw) return ''
  const { display, href } = normalizeUrl(raw)
  return `\\href{${esc(href)}}{${esc(display)}}`
}

export function generateLatex(data: ResumeData): string {
  const contactParts = [
    data.location,
    data.email   ? `\\href{mailto:${esc(data.email)}}{${esc(data.email)}}` : '',
    data.phone,
    linkPart(data.github),
    linkPart(data.linkedin),
    linkPart(data.portfolio),
  ].filter(Boolean).join(' $|$ ')

  const experienceBlocks = data.experience.map(exp => `
\\resumeSubheading
  {${esc(exp.role)}}{${esc(exp.period)}}
  {${esc(exp.company)}}{}
\\resumeItemListStart
${exp.bullets.map(b => `  \\resumeItem{${esc(b)}}`).join('\n')}
\\resumeItemListEnd`).join('\n')

  const projectBlocks = data.projects?.length ? `
\\section{Projects}
\\resumeSubHeadingListStart
${data.projects.map(p => `\\resumeProjectHeading
  {\\textbf{${esc(p.name)}} $|$ \\emph{${esc(p.tech)}}}{${linkPart(p.link)}}
\\resumeItemListStart
${p.bullets.map(b => `  \\resumeItem{${esc(b)}}`).join('\n')}
\\resumeItemListEnd`).join('\n')}
\\resumeSubHeadingListEnd` : ''

  const educationBlocks = data.education.map(ed => `\\resumeSubheading
  {${esc(ed.school)}}{${esc(ed.year)}}
  {${esc(ed.degree)}}{}`).join('\n')

  const skills = data.skills.map(s => esc(s.name)).join(', ')

  const publicationsSection = data.publications?.length ? `
\\section{Publications}
\\resumeItemListStart
${data.publications.map(p => `  \\resumeItem{${esc(p)}}`).join('\n')}
\\resumeItemListEnd` : ''

  const honorsSection = data.honors?.length ? `
\\section{Honors \\& Leadership}
\\resumeItemListStart
${data.honors.map(h => `  \\resumeItem{${esc(h)}}`).join('\n')}
\\resumeItemListEnd` : ''

  return `%-------------------------
% Resume in LaTeX — generated by ResumeMatch
% Based on Jake's Resume template (MIT License)
%-------------------------
\\documentclass[letterpaper,11pt]{article}

\\usepackage{latexsym}
\\usepackage[empty]{fullpage}
\\usepackage{titlesec}
\\usepackage{marvosym}
\\usepackage[usenames,dvipsnames]{color}
\\usepackage{verbatim}
\\usepackage{enumitem}
\\usepackage[hidelinks]{hyperref}
\\usepackage{fancyhdr}
\\usepackage[english]{babel}
\\usepackage{tabularx}

\\pagestyle{fancy}
\\fancyhf{}
\\fancyfoot{}
\\renewcommand{\\headrulewidth}{0pt}
\\renewcommand{\\footrulewidth}{0pt}

\\addtolength{\\oddsidemargin}{-0.5in}
\\addtolength{\\evensidemargin}{-0.5in}
\\addtolength{\\textwidth}{1in}
\\addtolength{\\topmargin}{-.5in}
\\addtolength{\\textheight}{1.0in}

\\urlstyle{same}
\\raggedbottom
\\raggedright
\\setlength{\\tabcolsep}{0in}

% Section formatting
\\titleformat{\\section}{\\vspace{-4pt}\\scshape\\raggedright\\large}{}{0em}{}[\\color{black}\\titlerule \\vspace{-5pt}]

% Custom commands
\\newcommand{\\resumeItem}[1]{\\item\\small{#1 \\vspace{-2pt}}}
\\newcommand{\\resumeSubheading}[4]{
  \\vspace{-2pt}\\item
  \\begin{tabular*}{0.97\\textwidth}[t]{l@{\\extracolsep{\\fill}}r}
    \\textbf{#1} & #2 \\\\
    \\textit{\\small#3} & \\textit{\\small #4} \\\\
  \\end{tabular*}\\vspace{-7pt}
}
\\newcommand{\\resumeProjectHeading}[2]{
  \\item
  \\begin{tabular*}{0.97\\textwidth}{l@{\\extracolsep{\\fill}}r}
    \\small#1 & #2 \\\\
  \\end{tabular*}\\vspace{-7pt}
}
\\newcommand{\\resumeSubHeadingListStart}{\\begin{itemize}[leftmargin=0.15in, label={}]}
\\newcommand{\\resumeSubHeadingListEnd}{\\end{itemize}}
\\newcommand{\\resumeItemListStart}{\\begin{itemize}}
\\newcommand{\\resumeItemListEnd}{\\end{itemize}\\vspace{-5pt}}

\\begin{document}

% ── HEADER ──────────────────────────────────────────────────────
\\begin{center}
  {\\Huge \\scshape ${esc(data.name)}} \\\\ \\vspace{1pt}
  \\small ${contactParts}
\\end{center}

% ── SUMMARY ─────────────────────────────────────────────────────
\\section{Summary}
${esc(data.summary)}

% ── EXPERIENCE ──────────────────────────────────────────────────
\\section{Experience}
\\resumeSubHeadingListStart
${experienceBlocks}
\\resumeSubHeadingListEnd
${projectBlocks}

% ── EDUCATION ───────────────────────────────────────────────────
\\section{Education}
\\resumeSubHeadingListStart
${educationBlocks}
\\resumeSubHeadingListEnd

% ── SKILLS ──────────────────────────────────────────────────────
\\section{Technical Skills}
\\begin{itemize}[leftmargin=0.15in, label={}]
  \\small{\\item{${skills}}}
\\end{itemize}
${publicationsSection}
${honorsSection}

\\end{document}
`
}
